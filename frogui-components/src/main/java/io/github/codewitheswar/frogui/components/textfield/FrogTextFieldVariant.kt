package io.github.codewitheswar.frogui.components.textfield

/**
 * Visual presentation style for [FrogTextField].
 */
public enum class FrogTextFieldVariant {
    /**
     * Filled container surface with subtle background differentiation and accent bottom indicator or border.
     */
    Filled,

    /**
     * Clear bounded container with a surrounding border outline.
     */
    Outline,

    /**
     * Minimal form surface with a prominent bottom divider/underline indicator.
     */
    Underline,
}
